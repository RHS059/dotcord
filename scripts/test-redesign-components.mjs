import {JSDOM} from 'jsdom';
import {build} from 'vite';
import react from '@vitejs/plugin-react';
import {viteSingleFile} from 'vite-plugin-singlefile';
import {readFileSync,mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {executeScripts,pause,until} from './helpers/redesign-dom.mjs';

const outDir=mkdtempSync(path.join(tmpdir(),'dotcord-components-'));
await build({configFile:false,root:path.resolve('scripts/fixtures/redesign-components'),plugins:[react(),viteSingleFile()],resolve:{alias:{'@':path.resolve('src')}},build:{outDir,emptyOutDir:true},logLevel:'warn'});
const dom=new JSDOM(readFileSync(path.join(outDir,'index.html'),'utf8'),{url:'https://synthetic.example.test/',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,d=w.document;
w.HTMLElement.prototype.scrollIntoView=function(){};
executeScripts(w,d.documentElement.outerHTML);
const key=(el,key)=>el.dispatchEvent(new w.KeyboardEvent('keydown',{key,bubbles:true,cancelable:true}));
const click=el=>el.dispatchEvent(new w.MouseEvent('click',{bubbles:true,cancelable:true}));
await until(()=>d.getElementById('first-select'));
const a=d.getElementById('first-select'),b=d.getElementById('second-select');
a.focus();key(a,'ArrowDown');await pause();
assert.equal(a.getAttribute('aria-expanded'),'true');
assert.equal(a.getAttribute('aria-activedescendant'),'first-select-opt-1');
assert.equal(d.activeElement,a,'Keyboard focus remains on trigger');
key(a,'End');await pause();assert.equal(a.getAttribute('aria-activedescendant'),'first-select-opt-2');
key(a,'ArrowDown');await pause();assert.equal(a.getAttribute('aria-activedescendant'),'first-select-opt-0','Arrows wrap');
key(a,'ArrowUp');await pause();assert.equal(a.getAttribute('aria-activedescendant'),'first-select-opt-2');
key(a,'Home');await pause();assert.equal(a.getAttribute('aria-activedescendant'),'first-select-opt-0');
key(a,'Enter');await pause();assert.equal(a.getAttribute('aria-expanded'),'false');assert.match(a.textContent,/Alpha/);
assert.ok(d.getElementById('first-select-list'),'Closed listbox stays mounted');
key(a,' ');await pause();key(a,'Escape');await pause();assert.equal(a.getAttribute('aria-expanded'),'false');
key(a,'ArrowUp');await pause();key(a,'Tab');await pause();assert.equal(a.getAttribute('aria-expanded'),'false');
click(a);await pause();click(b);await pause();assert.equal(a.getAttribute('aria-expanded'),'false');assert.equal(b.getAttribute('aria-expanded'),'true','Only one open app-wide');
d.getElementById('outside').dispatchEvent(new w.MouseEvent('mousedown',{bubbles:true}));await pause();assert.equal(b.getAttribute('aria-expanded'),'false');
click(a);await pause();const option=d.getElementById('first-select-opt-2');option.dispatchEvent(new w.MouseEvent('mousedown',{bubbles:true,cancelable:true}));await pause();assert.match(a.textContent,/Gamma/);assert.equal(d.activeElement,a);
for(const combo of d.querySelectorAll('[role=combobox]')){for(const id of combo.getAttribute('aria-labelledby').split(' '))assert.ok(d.getElementById(id),'ARIA label reference exists');assert.ok(d.getElementById(combo.getAttribute('aria-controls')));}
assert.equal(d.querySelectorAll('select').length,0);
click(d.getElementById('remove'));await pause();assert.equal(d.getElementById('remove-state').textContent,'removed / 0');
click(d.getElementById('notice'));await pause();
const undo=[...d.querySelectorAll('button')].find(b=>b.textContent==='Undo');
assert.ok(undo,'Undo remains available through the full grace period even if an unrelated toast fires');
click(undo);await pause();assert.equal(d.getElementById('remove-state').textContent,'present / 0');
dom.window.close();rmSync(outDir,{recursive:true,force:true});
console.log('PASS redesign component keyboard/ARIA, selection, outside dismissal, one-menu behavior, and protected Undo. Synthetic local fixture only.');
